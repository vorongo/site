window.detectLang = function(){
  const list = Array.isArray(navigator.languages) && navigator.languages.length
    ? navigator.languages
    : [navigator.language || navigator.userLanguage || "en"];
  for (const item of list) {
    const code = String(item || "").toLowerCase();
    if (code.startsWith("ru")) return "ru";
  }
  return "en";
};

window.getLang = function(){
  const saved = localStorage.getItem("vorongo-lang");
  if (saved === "en" || saved === "ru") return saved;
  return detectLang();
};

window.t = function(key){
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || (I18N.ru[key]) || key;
};

window.applyI18n = function(){
  const lang = getLang();
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key = el.getAttribute("data-i18n");
    const html = t(key);
    if (el.dataset.i18nHtml === "true") el.innerHTML = html;
    else el.textContent = html;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el=>{
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(el=>{
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  const titleKey = document.body.dataset.titleKey || "doc.title";
  document.title = t(titleKey);
  const langBtn = document.getElementById("lang-btn");
  if (langBtn) langBtn.textContent = lang === "en" ? "🇷🇺" : "🇬🇧";
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
};

window.initLangToggle = function(){
  const btn = document.getElementById("lang-btn");
  if (!btn) return;
  if (!localStorage.getItem("vorongo-lang")) {
    localStorage.setItem("vorongo-lang", detectLang());
  }
  btn.addEventListener("click", ()=>{
    localStorage.setItem("vorongo-lang", getLang() === "en" ? "ru" : "en");
    applyI18n();
  });
  applyI18n();
};

window.initMobileNav = function(){
  const nav = document.querySelector(".nav");
  const btn = document.getElementById("menu-btn");
  const drawer = document.getElementById("nav-drawer");
  if (!nav || !btn || !drawer) return;

  let backdrop = document.querySelector(".nav-backdrop");
  if (!backdrop) {
    backdrop = document.createElement("div");
    backdrop.className = "nav-backdrop";
    document.body.appendChild(backdrop);
  }

  function setOpen(open){
    nav.classList.toggle("is-open", open);
    backdrop.classList.toggle("is-open", open);
    document.body.classList.toggle("nav-open", open);
    btn.setAttribute("aria-expanded", open ? "true" : "false");
    btn.setAttribute("aria-label", t(open ? "nav.menu.close" : "nav.menu.aria"));
    btn.textContent = open ? "✕" : "☰";
  }

  btn.addEventListener("click", ()=> setOpen(!nav.classList.contains("is-open")));
  backdrop.addEventListener("click", ()=> setOpen(false));
  drawer.querySelectorAll("a").forEach(a=>{
    a.addEventListener("click", ()=> setOpen(false));
  });
  window.addEventListener("resize", ()=>{
    if (window.innerWidth > 650) setOpen(false);
  });
  document.addEventListener("keydown", e=>{
    if (e.key === "Escape") setOpen(false);
  });
  document.addEventListener("langchange", ()=>{
    const open = nav.classList.contains("is-open");
    btn.setAttribute("aria-label", t(open ? "nav.menu.close" : "nav.menu.aria"));
  });
};

window.initHeroRotator = function(){
  const el = document.getElementById("hero-rotator");
  if (!el) return;
  const slot = el.parentElement;

  let index = 0;
  let timer = null;
  let fading = false;
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const holdMs = 3800;
  const fadeMs = 550;

  function lines(){
    const lang = getLang();
    const list = (I18N[lang] && I18N[lang]["hero.rotator"]) || I18N.ru["hero.rotator"] || [];
    return Array.isArray(list) ? list : [];
  }

  function syncHeight(){
    if (!slot) return;
    const items = lines();
    if (!items.length) return;
    const current = el.innerHTML;
    const wasFading = el.classList.contains("is-fading");
    el.classList.remove("is-fading");
    slot.style.minHeight = "0";
    let max = 0;
    items.forEach(html=>{
      el.innerHTML = html;
      max = Math.max(max, el.offsetHeight);
    });
    el.innerHTML = current;
    if (wasFading) el.classList.add("is-fading");
    slot.style.minHeight = max + "px";
  }

  function show(i){
    const items = lines();
    if (!items.length) return;
    index = ((i % items.length) + items.length) % items.length;
    el.innerHTML = items[index];
  }

  function stop(){
    if (timer) {
      clearTimeout(timer);
      timer = null;
    }
  }

  function scheduleNext(){
    stop();
    if (reduceMotion || lines().length < 2) return;
    timer = setTimeout(next, holdMs);
  }

  function next(){
    if (fading) return;
    const items = lines();
    if (items.length < 2) return;
    fading = true;
    el.classList.add("is-fading");
    timer = setTimeout(()=>{
      show(index + 1);
      void el.offsetWidth;
      el.classList.remove("is-fading");
      fading = false;
      scheduleNext();
    }, fadeMs);
  }

  show(0);
  syncHeight();
  scheduleNext();

  let resizeTimer = null;
  window.addEventListener("resize", ()=>{
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(syncHeight, 120);
  });

  document.addEventListener("langchange", ()=>{
    stop();
    fading = false;
    el.classList.remove("is-fading");
    show(0);
    syncHeight();
    scheduleNext();
  });
};

window.initHeroArtSlides = function(){
  const root = document.getElementById("hero-art");
  const caption = document.getElementById("hero-art-caption");
  if (!root || !caption) return;
  const slides = Array.from(root.querySelectorAll(".hero-slide"));
  if (slides.length < 2) return;

  const keys = ["hero.caption", "hero.caption.cat"];
  let index = 0;
  let timer = null;
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  const holdMs = 5200;
  const fadeMs = 350;

  function paint(){
    slides.forEach((slide, i)=>slide.classList.toggle("is-active", i === index));
    caption.textContent = t(keys[index] || keys[0]);
  }

  function next(){
    if (reduceMotion) {
      index = (index + 1) % slides.length;
      paint();
      return;
    }
    caption.classList.add("is-fading");
    setTimeout(()=>{
      index = (index + 1) % slides.length;
      paint();
      caption.classList.remove("is-fading");
    }, fadeMs);
  }

  function schedule(){
    clearTimeout(timer);
    timer = setTimeout(()=>{
      next();
      schedule();
    }, holdMs);
  }

  paint();
  schedule();
  document.addEventListener("langchange", paint);
};


window.fmtGameDate = function(s){
  const lang = (typeof getLang === "function" ? getLang() : "ru");
  const d = new Date(s + "T12:00:00");
  return d.toLocaleDateString(lang === "ru" ? "ru-RU" : "en-US", { day: "numeric", month: "short", year: "numeric" });
};

window.renderGameCard = function(g){
  const lang = (typeof getLang === "function" ? getLang() : "ru");
  const type = typeof g.type === "object" ? (g.type[lang] || g.type.ru) : g.type;
  const desc = typeof g.desc === "object" ? (g.desc[lang] || g.desc.ru) : g.desc;
  const statusKey = g.statusKey || ("status." + g.status);
  const statusLabel = (typeof t === "function" ? t(statusKey) : g.status);
  const media = g.cover
    ? `<img src="${g.cover}" alt="${g.title}" loading="lazy" draggable="false">`
    : `<div class="fake">${g.fake || "🎮"}</div>`;
  const place = g.place
    ? `<span class="jam-place${g.placeWin ? " win" : ""}">${g.place}</span>`
    : "";
  const pubLabel = lang === "ru" ? "Опубликовано" : "Published";
  const updLabel = lang === "ru" ? "Обновлено" : "Updated";
  const dates = (g.published || g.updated)
    ? `<div class="game-dates">${g.published ? `<span>${pubLabel}: ${fmtGameDate(g.published)}</span>` : ""}${g.updated ? ` · <span>${updLabel}: ${fmtGameDate(g.updated)}</span>` : ""}</div>`
    : "";
  const statusClass = g.status === "finished" ? "released" : g.status;
  return `<a class="game" href="${g.href}" target="_blank" rel="noopener" data-status="${g.status}" data-title="${g.title.toLowerCase()}">
    <div class="game-img">${media}${place}</div>
    <div class="game-body">
      <h3>${g.title}</h3>
      <div class="type">${type}</div>
      <p>${desc}</p>
      ${dates}
      <div class="game-foot"><span>${g.store}</span><span class="status ${statusClass}">${statusLabel}</span></div>
    </div>
  </a>`;
};

window.renderJamRow = function(j){
  const lang = (typeof getLang === "function" ? getLang() : "ru");
  const desc = typeof j.desc === "object" ? (j.desc[lang] || j.desc.ru) : j.desc;
  const badgeKey = j.role === "winner"
    ? "jam.winner"
    : j.role === "prizewinner"
      ? "jam.prizewinner"
      : "jam.participant";
  const badgeClass = (j.role === "winner" || j.role === "prizewinner") ? "badge win" : "badge";
  const badge = typeof t === "function" ? t(badgeKey) : j.role;
  const placeLabel = typeof t === "function" ? t("jam.place") : "Place:";
  return `<a class="jam" href="${j.href}" target="_blank" rel="noopener" data-role="${j.role}" data-title="${j.title.toLowerCase()}" data-game="${(j.game || "").toLowerCase()}">
    <div class="jam-thumb"><img src="${j.cover}" alt="${j.title}" loading="lazy" draggable="false"></div>
    <div class="jam-main"><b>${j.title}</b><span class="${badgeClass}">${badge}</span><p>${desc}</p></div>
    <div class="jam-side">${j.year}<br><span>${placeLabel}</span> ${j.place}</div>
  </a>`;
};
